/**
 * Build the two faces of the bundle.
 *
 * Host face: one ESM file at lib/host/index.js. Bare imports (Cordis,
 * schemastery, dsh-* packages) stay external because the DSH profile resolves
 * them; relative modules are inlined.
 *
 * Client face: the Web module loader expects `window.__ModuleLoader__.load({
 * id, factory(require) })`, so the esbuild CommonJS bundle is wrapped in that
 * envelope. React and react/jsx-runtime stay external and are supplied by the
 * page's baseline module table.
 *
 * Types: `tsc --emitDeclarationOnly` produces the public `.d.ts` tree used by
 * package.json exports.
 */

import { execFileSync } from 'node:child_process'
import { mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const lib = join(root, 'lib')
const pkg = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'))

/** Fail before touching lib/ when the workspace lacks a required build tool. */
async function requireTool(relativePath, installHint) {
  try {
    await readFile(join(root, relativePath))
  } catch {
    throw new Error(`missing ${relativePath}. Run \`npm install\` first (${installHint}).`)
  }
}

await requireTool('node_modules/typescript/bin/tsc', 'typescript')
await requireTool('node_modules/esbuild/package.json', 'esbuild')

await rm(lib, { recursive: true, force: true })
await mkdir(lib, { recursive: true })

/** Host entry: single-file ESM, external bare packages. */
await build({
  entryPoints: [join(root, 'src/host/index.ts')],
  outfile: join(lib, 'host/index.js'),
  bundle: true,
  packages: 'external',
  platform: 'node',
  format: 'esm',
  target: 'node24',
  sourcemap: true,
  logLevel: 'info',
})

/** Public type tree, including the shared protocol declarations. */
execFileSync(
  process.execPath,
  [
    join(root, 'node_modules/typescript/bin/tsc'),
    '-p', join(root, 'tsconfig.json'),
    '--emitDeclarationOnly',
    '--declaration', '--declarationMap',
    '--outDir', join(lib, 'types'),
  ],
  { cwd: root, stdio: 'inherit' },
)

/**
 * `rewriteRelativeImportExtensions` rewrites emitted JavaScript but not the
 * declaration tree. Consumers resolve `./x.js` to `x.d.ts`; leaving `./x.ts`
 * would point at source files the published package does not ship.
 */
async function rewriteDeclarationSpecifiers(directory) {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name)
    if (entry.isDirectory()) {
      await rewriteDeclarationSpecifiers(path)
      continue
    }
    if (!entry.name.endsWith('.d.ts')) continue
    const source = await readFile(path, 'utf8')
    const rewritten = source
      .replace(/(\bfrom\s+['"][^'"]+)\.(?:ts|tsx)(['"])/g, '$1.js$2')
      .replace(/(\bimport\(\s*['"][^'"]+)\.(?:ts|tsx)(['"]\s*\))/g, '$1.js$2')
    if (rewritten !== source) await writeFile(path, rewritten, 'utf8')
  }
}

await rewriteDeclarationSpecifiers(join(lib, 'types'))

/** Client entry: CJS bundle wrapped in the loader factory envelope. */
const client = await build({
  entryPoints: [join(root, 'src/client/index.tsx')],
  bundle: true,
  write: false,
  platform: 'browser',
  format: 'cjs',
  target: 'es2022',
  jsx: 'automatic',
  external: ['react', 'react/jsx-runtime'],
  define: { 'process.env.NODE_ENV': '"production"' },
  legalComments: 'none',
  logLevel: 'info',
})

const clientCode = client.outputFiles?.[0]?.text
if (clientCode === undefined) throw new Error('esbuild produced no client output')

const wrapped = `/* Generated by scripts/build.mjs. Do not edit. */
window.__ModuleLoader__.load({
  id: ${JSON.stringify(pkg.name)},
  factory(require) {
    var module = { exports: {} };
    var exports = module.exports;
${clientCode}
    return module.exports;
  },
});
`
await writeFile(join(lib, 'client.js'), wrapped, 'utf8')

console.log(`built ${pkg.name}: lib/host/index.js, lib/client.js, lib/types/**`)
